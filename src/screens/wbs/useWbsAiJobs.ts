/**
 * The WBS Builder's AI jobs (generate and validate) and when they start by themselves.
 *
 * Purpose: A project without a WBS gets one AI draft from its accepted scope, and a WBS gets one
 * AI review when it has none; edits never re-run the review because it costs tokens (the free
 * built-in checks cover edits). Nothing is generated before a scope item is accepted (the page
 * says to accept the scope first), and a generation that failed before the scope was accepted is
 * retried once instead of showing that old failure; every other failure waits for Try again.
 * How it fits: Used by `screens/WBSBuilder.tsx`; wraps `useLatestAiJob` and `useStartAiJob` from
 * `lib/queries` and reads the scope items' status; layer: screen.
 * Created: 2026-11-14 · Version: 1.0 (NirnAIn demo release)
 */

import { useEffect, useRef } from 'react'
import { isRunning, useLatestAiJob, useStartAiJob, type useScopeItems, type useWbs } from '@/lib/queries'
import type { AiJob, ScopeItem } from '@/lib/types'

/**
 * A failed generation that predates the accepted scope: an item was accepted (or added accepted)
 * after the job was created, so the job never saw it. The product owner's case: step 4 opened
 * before the intake ran failed with "Accept at least one scope item", then she accepted 27 items.
 */
function failedBeforeScope(job: AiJob | null | undefined, accepted: ScopeItem[]): boolean {
  if (job?.status !== 'failed') return false
  const created = Date.parse(job.createdAt)
  return accepted.some((item) => Date.parse(item.updatedAt) > created)
}

/**
 * The WBS Builder's two AI jobs and when they start by themselves: one generation per visit when
 * the project has no WBS but has accepted scope (and either no generation yet, or only one that
 * failed before that scope was accepted), a reload of the tree when a generation finishes, and one
 * AI review when there is none yet. Edits never re-run the review: it costs tokens, and the free
 * checks cover edits.
 */
export function useWbsAiJobs(
  projectId: string,
  wbsQuery: ReturnType<typeof useWbs>,
  scopeQuery: ReturnType<typeof useScopeItems>,
  nodeCount: number,
) {
  const generateJob = useLatestAiJob(projectId, 'wbs_generate')
  const validateJob = useLatestAiJob(projectId, 'wbs_validate')
  const startGenerate = useStartAiJob(projectId, 'wbs_generate')
  const startValidate = useStartAiJob(projectId, 'wbs_validate')

  const generateStatus = generateJob.data?.status
  const accepted = scopeQuery.isSuccess ? scopeQuery.data.filter((item) => item.status === 'accepted') : null
  const wbsEmpty = wbsQuery.isSuccess && wbsQuery.data.length === 0
  // Known for sure: the WBS is empty and no scope item is accepted, so there is nothing to draft from.
  const needsScope = wbsEmpty && accepted !== null && accepted.length === 0
  // The draft this visit starts (or is about to start) by itself; never while a job is running.
  const autoGenerateDue =
    wbsEmpty &&
    generateJob.isSuccess &&
    accepted !== null &&
    accepted.length > 0 &&
    (generateJob.data === null || failedBeforeScope(generateJob.data, accepted))
  // While the start is due, show "building" rather than the old failure it replaces; if the start
  // itself fails, its error shows instead.
  const generating = startGenerate.isPending || isRunning(generateStatus) || (autoGenerateDue && !startGenerate.isError)
  const validating = startValidate.isPending || isRunning(validateJob.data?.status)

  // "AI has pre-populated based on scope": at most one automatic start per visit, so a failing
  // generation can't loop (each try may cost tokens). Decide on settled data only.
  const autoGenerated = useRef(false)
  const settled = !wbsQuery.isFetching && !generateJob.isFetching && !scopeQuery.isFetching
  useEffect(() => {
    if (autoGenerated.current || !settled || !autoGenerateDue || startGenerate.isPending) return
    autoGenerated.current = true
    startGenerate.mutate()
  }, [settled, autoGenerateDue, startGenerate])

  // A generation that just finished: load the new tree.
  const lastGenerateStatus = useRef(generateStatus)
  useEffect(() => {
    const previous = lastGenerateStatus.current
    lastGenerateStatus.current = generateStatus
    if (previous && isRunning(previous) && generateStatus === 'succeeded') void wbsQuery.refetch()
  }, [generateStatus, wbsQuery])

  // One AI review automatically when there is none yet; edits never re-run it (it costs tokens).
  const autoValidated = useRef(false)
  useEffect(() => {
    if (autoValidated.current || generating || !validateJob.isSuccess || nodeCount === 0) return
    if (validateJob.data === null) {
      autoValidated.current = true
      startValidate.mutate()
    }
  }, [generating, validateJob.isSuccess, validateJob.data, nodeCount, startValidate])

  return { generateJob, validateJob, startGenerate, startValidate, generateStatus, generating, validating, needsScope }
}
